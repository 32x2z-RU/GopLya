def format_message(code: str, **kwargs) -> str:
    """Форматирует сообщение по коду с подстановкой параметров."""
    template = MESSAGES.get(code)
    if template is None:
        return f"[Неизвестный код {code}]"
    try:
        return template.format(**kwargs)
    except KeyError as e:
        return f"[Ошибка форматирования {code}: отсутствует параметр {e}]"


def error_msg(code: str, line: int, **kwargs) -> str:
    """Форматирует ошибку компиляции: 'Ошибка: <фраза> Строка N.'"""
    phrase = format_message(code, **kwargs)
    return f"Ошибка: {phrase} Строка {line}."


def warning_msg(code: str, line: int, **kwargs) -> str:
    """Форматирует предупреждение: 'Предупреждение: <фраза> Строка N.'"""
    phrase = format_message(code, **kwargs)
    return f"Предупреждение: {phrase} Строка {line}."


def runtime_msg(code: str, **kwargs) -> str:
    """Форматирует сообщение ошибки выполнения."""
    return format_message(code, **kwargs)


# Падежи типов для E009 (родительный падеж)
TYPE_GENITIVE = {
    "целое": "целого",
    "дробь": "дроби",
    "текст": "текста",
    "логика": "логики",
    "пусто": "пусто",
    "кучка": "кучки",
    "общак": "общака",
}


def type_genitive(type_name: str) -> str:
    """Возвращает тип в родительном падеже для E009."""
    # Пользовательские гопы: «Х» в кавычках
    if type_name not in TYPE_GENITIVE:
        return f"«{type_name}»"
    return TYPE_GENITIVE[type_name]